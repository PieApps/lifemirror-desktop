import type { ActivityNode, DailySummary } from "../types";
import { type ProductivityMetrics, formatDuration } from "./analytics";
import { mapAppToCategory } from "../utils/categoryMapper";

/**
 * Generates a Markdown-formatted daily work journal.
 */
export function generateMarkdownJournal(
  date: string,
  activities: ActivityNode[],
  metrics: ProductivityMetrics
): string {
  const d = new Date(date);
  const formattedDate = d.toLocaleDateString(undefined, {
    weekday: "long",
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  // Calculate high-level breakdown
  const focusTime = metrics.deepWorkTime + metrics.browsingTime;
  const commsTime = metrics.communicationTime;
  const distTime = metrics.distractionTime;
  const switches = metrics.contextSwitches;

  let md = `# Daily Work Journal: ${formattedDate}\n\n`;

  // ── 1. Top-line Metrics ──
  md += `## Overview\n`;
  md += `- **Productivity Score**: ${metrics.score}/100 (${metrics.scoreLabel})\n`;
  md += `- **Focus Time**: ${formatDuration(focusTime)}\n`;
  md += `- **Communication/Meetings**: ${formatDuration(commsTime)}\n`;
  md += `- **Distractions**: ${formatDuration(distTime)}\n`;
  md += `- **Context Switches**: ${switches}\n\n`;

  // ── 2. Detailed Work Log ──
  md += `## Work Log\n`;
  
  if (metrics.topApps.length > 0) {
    for (const app of metrics.topApps) {
      if (app.category !== "entertainment") {
        md += `- **${app.appName}**: ${formatDuration(app.duration)}\n`;
      }
    }
  } else {
    md += `*No significant work recorded.*\n`;
  }
  md += `\n`;

  // ── 3. Personal Notes / Journal Entries ──
  const activitiesWithNotes = activities
    .filter((a) => a.notes && a.notes.trim() !== "")
    .sort((a, b) => new Date(a.start_time).getTime() - new Date(b.start_time).getTime());

  if (activitiesWithNotes.length > 0) {
    md += `## Personal Notes & Milestones\n`;
    for (const act of activitiesWithNotes) {
      const timeStr = new Date(act.start_time).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
      // Clean up multiline notes to preserve formatting
      const cleanNotes = act.notes?.trim().split('\n').map(line => `  > ${line}`).join('\n') || '';
      md += `- **[${timeStr}] ${act.app_name}** - ${act.window_title}\n${cleanNotes}\n`;
    }
    md += `\n`;
  }

  // ── Footer ──
  md += `---\n*Generated by LifeMirror Desktop*`;

  return md;
}

/**
 * Generates a Markdown-formatted weekly or monthly work journal.
 */
export function generateAggregateJournal(
  _date: string,
  summaries: DailySummary[],
  period: "Weekly" | "Monthly"
): string {
  // Calculate high-level breakdown
  let focusTime = 0;
  let commsTime = 0;
  let distTime = 0;
  const appDurations: Record<string, number> = {};

  for (const s of summaries) {
    const dur = s.total_duration;
    const appName = s.app_name;
    appDurations[appName] = (appDurations[appName] || 0) + dur;

    const category = mapAppToCategory(appName);
    if (category === "development" || category === "browser" || category === "other") {
      focusTime += dur;
    } else if (category === "communication") {
      commsTime += dur;
    } else if (category === "entertainment") {
      distTime += dur;
    }
  }

  const topApps = Object.entries(appDurations)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 10);

  let md = `# ${period} Work Journal\n\n`;

  // ── 1. Top-line Metrics ──
  md += `## Overview\n`;
  md += `- **Focus Time**: ${formatDuration(focusTime)}\n`;
  md += `- **Communication/Meetings**: ${formatDuration(commsTime)}\n`;
  md += `- **Distractions (Entertainment)**: ${formatDuration(distTime)}\n\n`;

  // ── 2. Detailed Work Log ──
  md += `## Top Applications\n`;
  
  if (topApps.length > 0) {
    for (const [appName, dur] of topApps) {
      md += `- **${appName}**: ${formatDuration(dur)}\n`;
    }
  } else {
    md += `*No significant work recorded.*\n`;
  }
  md += `\n`;

  // ── Footer ──
  md += `---\n*Generated by LifeMirror Desktop*`;

  return md;
}
